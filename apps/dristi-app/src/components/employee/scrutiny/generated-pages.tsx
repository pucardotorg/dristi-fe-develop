/**
 * Paper facsimiles of the three generated bundle pages.
 *
 * These are not product chrome — they are what the complaint PDF looks like, so they use
 * the DS's `paper-*` family (`paper`, `paper-foreground`, `paper-muted-foreground`,
 * `paper-border`) and nothing else. The scanned affidavit carries the blurred paragraph
 * the officer is meant to catch.
 */
const PAGE =
  "min-h-[34rem] bg-paper px-12 py-10 text-body-compact leading-relaxed text-paper-foreground";
const HEADING = "text-center text-body-compact font-bold tracking-wide";
